#!/usr/bin/env python3
"""Generate the per-route HTML files, legacy redirect stubs, 404.html, sitemap.xml and robots.txt.

Single source of truth: live-site/index.html. Its <script type="application/json" id="eltek-routes">
block holds the route table (paths, titles, descriptions, legacy redirects, business facts for
JSON-LD). Edit index.html (markup, CSS, logic or that JSON), then run from live-site/:

    python tools/build-routes.py          # regenerate everything
    python tools/build-routes.py --check  # exit 1 if any generated file is out of date

Standard library only. Output is written with LF line endings.
"""
import argparse
import datetime
import hashlib
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "index.html")
STATE = os.path.join(ROOT, "tools", "sitemap-state.json")
MARKER = "<!-- GENERATED by tools/build-routes.py from /index.html. Do not edit: edit index.html and re-run. -->"
HEAD_RE = re.compile(r"(<!-- SEO:HEAD:START[^>]*-->\n)(.*?)(<!-- SEO:HEAD:END -->)", re.S)
ROUTES_RE = re.compile(r'<script type="application/json" id="eltek-routes">(.*?)</script>', re.S)


def esc(value):
    return html.escape(str(value), quote=True)


def read(path):
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read().replace("\r\n", "\n")


def json_ld(cfg):
    org = cfg["organization"]
    site = cfg["site"]
    graph = [
        dict({"@type": org["type"], "@id": site + "/#organization", "url": site + "/"},
             **{k: v for k, v in org.items() if k != "type"}),
        {
            "@type": "WebSite",
            "@id": site + "/#website",
            "url": site + "/",
            "name": cfg["siteName"],
            "publisher": {"@id": site + "/#organization"},
        },
    ]
    data = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False, indent=2)
    return data.replace("<", "\\u003c")


def head_block(cfg, route):
    site = cfg["site"]
    lines = []
    if route is None:
        nf = cfg["notFound"]
        lines += [
            "<title>%s</title>" % esc(nf["title"]),
            '<meta name="description" content="%s">' % esc(nf["description"]),
            '<meta name="robots" content="noindex">',
        ]
        if cfg.get("favicon"):
            lines.append('<link rel="icon" href="%s" sizes="any">' % esc(cfg["favicon"]))
            lines.append('<link rel="icon" type="image/png" sizes="48x48" href="/favicon-48.png">')
        return "\n".join(lines) + "\n"
    url = site + route["path"]
    img = cfg["ogImage"]
    img_url = site + img["path"]
    lines += [
        "<title>%s</title>" % esc(route["title"]),
        '<meta name="description" content="%s">' % esc(route["description"]),
        '<link rel="canonical" href="%s">' % esc(url),
    ]
    if route.get("noindex"):
        lines.append('<meta name="robots" content="noindex">')
    if cfg.get("favicon"):
        lines.append('<link rel="icon" href="%s" sizes="any">' % esc(cfg["favicon"]))
        lines.append('<link rel="icon" type="image/png" sizes="48x48" href="/favicon-48.png">')
    lines += [
        '<meta property="og:type" content="website">',
        '<meta property="og:site_name" content="%s">' % esc(cfg["siteName"]),
        '<meta property="og:locale" content="en_US">',
        '<meta property="og:title" content="%s">' % esc(route["title"]),
        '<meta property="og:description" content="%s">' % esc(route["description"]),
        '<meta property="og:url" content="%s">' % esc(url),
        '<meta property="og:image" content="%s">' % esc(img_url),
        '<meta property="og:image:width" content="%s">' % esc(img["width"]),
        '<meta property="og:image:height" content="%s">' % esc(img["height"]),
        '<meta property="og:image:alt" content="%s">' % esc(img["alt"]),
        '<meta name="twitter:card" content="summary_large_image">',
        '<meta name="twitter:title" content="%s">' % esc(route["title"]),
        '<meta name="twitter:description" content="%s">' % esc(route["description"]),
        '<meta name="twitter:image" content="%s">' % esc(img_url),
        '<meta name="twitter:image:alt" content="%s">' % esc(img["alt"]),
    ]
    if route["path"] == "/" and cfg.get("organization"):
        lines.append('<script type="application/ld+json">\n%s\n</script>' % json_ld(cfg))
    return "\n".join(lines) + "\n"


def with_head(source, block):
    out, n = HEAD_RE.subn(lambda m: m.group(1) + block + m.group(3), source, count=1)
    if n != 1:
        sys.exit("ERROR: SEO:HEAD markers not found in index.html")
    return out


def with_marker(page):
    if not page.startswith("<!DOCTYPE html>\n"):
        sys.exit("ERROR: index.html must start with '<!DOCTYPE html>'")
    return page.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + MARKER + "\n", 1)


def stub(cfg, old, new):
    site = cfg["site"]
    target = next((r for r in cfg["routes"] if r["path"] == new), None)
    if target is None:
        sys.exit("ERROR: legacy target %s is not a route" % new)
    name = target.get("nav") or target["title"]
    return "\n".join([
        "<!DOCTYPE html>",
        MARKER,
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>%s</title>" % esc(target["title"]),
        '<link rel="canonical" href="%s">' % esc(site + new),
        '<meta http-equiv="refresh" content="0; url=%s">' % esc(new),
        "<script>location.replace(%s + location.hash);</script>" % json.dumps(new),
        "<style>body{margin:0;padding:40px 20px;background:#EFECE6;color:#15171A;font-family:Barlow,Arial,sans-serif;font-size:17px}</style>",
        "</head>",
        "<body>",
        '<p>This page has moved to <a href="%s">%s</a>.</p>' % (esc(new), esc(name)),
        "</body>",
        "</html>",
        "",
    ])


def build(cfg, source):
    files = {}
    paths = [r["path"] for r in cfg["routes"]]
    for route in cfg["routes"]:
        page = with_head(source, head_block(cfg, route))
        if route["path"] == "/":
            files["index.html"] = page
        else:
            files[route["path"].strip("/") + "/index.html"] = with_marker(page)
    files["404.html"] = with_marker(with_head(source, head_block(cfg, None)))
    for item in cfg.get("legacy", []):
        if item["from"] in paths:
            sys.exit("ERROR: legacy path %s collides with a route" % item["from"])
        files[item["from"].strip("/") + "/index.html"] = stub(cfg, item["from"], item["to"])
    files["robots.txt"] = "User-agent: *\nAllow: /\n\nSitemap: %s/sitemap.xml\n" % cfg["site"]
    return files


def sitemap(cfg, files, state, today):
    new_state = {}
    entries = []
    for route in cfg["routes"]:
        if route.get("noindex"):
            continue
        key = "index.html" if route["path"] == "/" else route["path"].strip("/") + "/index.html"
        digest = hashlib.sha256(files[key].encode("utf-8")).hexdigest()
        prev = state.get(route["path"], {})
        lastmod = prev.get("lastmod") if prev.get("sha256") == digest else today
        new_state[route["path"]] = {"sha256": digest, "lastmod": lastmod}
        entries.append("  <url>\n    <loc>%s</loc>\n    <lastmod>%s</lastmod>\n  </url>" % (esc(cfg["site"] + route["path"]), lastmod))
    xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n%s\n</urlset>\n' % "\n".join(entries)
    return xml, new_state


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report out-of-date files and exit 1, write nothing")
    ap.add_argument("--force", action="store_true", help="overwrite files that lack the GENERATED marker")
    args = ap.parse_args()

    source = read(SOURCE)
    match = ROUTES_RE.search(source)
    if not match:
        sys.exit("ERROR: eltek-routes JSON block not found in index.html")
    cfg = json.loads(match.group(1))
    if os.path.exists(os.path.join(ROOT, "favicon.ico")):
        cfg["favicon"] = "/favicon.ico"

    files = build(cfg, source)
    state = {}
    if os.path.exists(STATE):
        state = json.loads(read(STATE))
    today = datetime.date.today().isoformat()
    files["sitemap.xml"], new_state = sitemap(cfg, files, state, today)
    files["tools/sitemap-state.json"] = json.dumps(new_state, indent=2, sort_keys=True) + "\n"

    stale = []
    for rel, content in sorted(files.items()):
        path = os.path.join(ROOT, *rel.split("/"))
        current = read(path) if os.path.exists(path) else None
        if current == content:
            continue
        stale.append(rel)
        if args.check:
            continue
        guarded = rel not in ("index.html", "robots.txt", "sitemap.xml", "tools/sitemap-state.json")
        if current is not None and guarded and MARKER not in current and not args.force:
            sys.exit("ERROR: %s exists and was not generated by this script (use --force)" % rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)

    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale))
            sys.exit(1)
        print("All generated files are up to date (%d files)." % len(files))
    else:
        print("Updated: " + (", ".join(stale) if stale else "nothing, all up to date"))


if __name__ == "__main__":
    main()
